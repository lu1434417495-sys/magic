def count_cjk(text: str) -> int:
    return len(re.findall(r"[\u4e00-\u9fff]", text))


def process_file(index: int) -> None:
    filename = f"book_战士战技_{index:04d}.md"
    path = os.path.join(OUTPUT_DIR, filename)
    if not os.path.exists(path):
        print(f"SKIP: {filename} not found")
        return

    with open(path, "r", encoding="utf-8") as f:
        text = f.read()

    parts = text.split("## 书籍内容")
    if len(parts) != 2:
        print(f"WARN: {filename} has unexpected '## 书籍内容' split count {len(parts)}")
        return

    head, rest = parts
    content_parts = rest.split("## 设计意图")
    if len(content_parts) != 2:
        print(f"WARN: {filename} has unexpected '## 设计意图' split count {len(content_parts)}")
        return

    content, tail = content_parts
    content = content.strip()
    expansion = EXPANSIONS.get(index, "")
    if not expansion:
        print(f"WARN: no expansion for book {index}")
        return

    new_content = f"{content}\n\n{expansion}"
    new_cjk = count_cjk(new_content)

    if not (280 <= new_cjk <= 330):
        print(f"WARN: {filename} content CJK count = {new_cjk}")

    new_text = f"{head}## 书籍内容\n\n{new_content}\n\n## 设计意图{tail}"
    with open(path, "w", encoding="utf-8") as f:
        f.write(new_text)
    print(f"OK: {filename} -> {new_cjk} CJK chars")


def main() -> None:
    for i in range(START, START + COUNT):
        process_file(i)


if __name__ == "__main__":
    main()
