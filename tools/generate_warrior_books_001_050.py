def count_chinese(text: str) -> int:
    """Count CJK characters roughly."""
    return len(re.findall(r"[\u4e00-\u9fff]", text))


def make_filename(index: int) -> str:
    return f"book_{SERIES_NAME}_{index:04d}.md"


def render_book(index: int, entry: tuple) -> str:
    title, skill_id, effect, requirement, rarity, drop, content, design_intent = entry
    book_id = f"book_{SERIES_NAME}_{index:04d}"
    return f"""# {title}

## 基础信息

- **书籍 ID**：`{book_id}`
- **关联技能**：`{skill_id}`
- **使用效果**：{effect}
- **阅读要求**：{requirement}
- **稀有度**：{rarity}
- **建议投放**：{drop}

## 书籍内容

{content}

## 设计意图

{design_intent}
"""


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    assert len(BOOKS) == COUNT, f"Expected {COUNT} books, got {len(BOOKS)}"

    generated = 0
    for i, entry in enumerate(BOOKS, start=START_INDEX):
        content = render_book(i, entry)
        # Quick sanity check on Chinese character count for the content section.
        body_text = entry[6]
        cn_count = count_chinese(body_text)
        if not (280 <= cn_count <= 330):
            print(f"WARN: book {i} content CJK count = {cn_count}")
        path = os.path.join(OUTPUT_DIR, make_filename(i))
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        generated += 1

    print(f"Generated {generated} books in {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
