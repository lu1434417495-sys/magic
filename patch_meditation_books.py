def patch_file(index: int) -> None:
    path = os.path.join(OUTPUT_DIR, f"book_meditation_{index:04d}.md")
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    start = text.find("## 书籍内容\n\n")
    end = text.find("\n\n## 设计意图")
    if start == -1 or end == -1:
        print(f"SKIP: {path}")
        return
    prefix = text[:start + len("## 书籍内容\n\n")]
    content = text[start + len("## 书籍内容\n\n"):end]
    suffix = text[end:]

    extra = EXTRA_SENTENCES.get(index, "")
    if extra and extra not in content:
        content = content.rstrip() + extra + "\n"

    ch = len(re.findall(r"[\u4e00-\u9fff]", content))
    with open(path, "w", encoding="utf-8") as f:
        f.write(prefix + content + suffix)
    print(f"{index}: ch={ch}")


def main():
    for i in range(51, 101):
        patch_file(i)


if __name__ == "__main__":
    main()
