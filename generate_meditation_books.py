def zh_len(text: str) -> int:
    return len(text)


def render(book: dict, index: int) -> str:
    book_id = f"book_{SERIES}_{index:04d}"
    return f"""# {book['title']}

## 基础信息

- **书籍 ID**：`{book_id}`
- **关联技能**：`{book['skill_id']}`（待新增，标签 `{SERIES}`）
- **使用效果**：{book['effect']}
- **阅读要求**：{book['requirements']}
- **稀有度**：{book['rarity']}
- **建议投放**：{book['distribution']}

## 书籍内容

{book['content']}

## 设计意图

{book['design_intent']}
"""


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    created = 0
    for i, book in enumerate(BOOKS, start=START_INDEX):
        path = os.path.join(OUTPUT_DIR, f"book_{SERIES}_{i:04d}.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(book, i))
        created += 1
        content_len = zh_len(book["content"])
        if content_len < 280 or content_len > 330:
            print(f"WARN: {path} content length {content_len}")
    print(f"Created {created} files in {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
